"""Phase 12 documents: RESULTS.md and MODEL_CARD.md (PLAN.md section 13).

RESULTS.md is generated by scripts/make_results.py and never edited by hand. It holds
only measured numbers, each with its date, model ID and sample size. The plan's test:
run the project's own number verifier over RESULTS.md against the source files.
"""

from __future__ import annotations

import importlib.util
import json
import re

from tenorwise.agent.loop import MAX_MODEL_CALLS, MAX_QUESTION_CHARS
from tenorwise.agent.verifier import RELATIVE_TOLERANCE
from tests.doc_numbers import EVALS, QUANTLIB, REPO, eval_ledger, quantlib_values, untraced


def make_results():
    spec = importlib.util.spec_from_file_location("make_results", REPO / "scripts" / "make_results.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def sources():
    led, dates = eval_ledger()
    quantlib_values(led)
    report = json.loads(QUANTLIB.read_text())
    dates.update({report["generated_at"][:10], report["data_date"]})
    return led, dates


# ------------------------------------------------------------------ RESULTS.md


def test_results_md_is_generated_and_current():
    assert (REPO / "RESULTS.md").read_text(encoding="utf-8") == make_results().render(), \
        "RESULTS.md is generated: run uv run python scripts/make_results.py"


def test_every_number_in_results_md_passes_the_verifier_against_the_source_files():
    led, dates = sources()
    assert untraced((REPO / "RESULTS.md").read_text(encoding="utf-8"), led, dates) == []


def test_the_check_rejects_an_invented_figure():
    led, dates = sources()
    assert untraced("Agrees to 1.23 × 10⁻¹³ and scores 99.1% at $0.0123.", led, dates) == ["1.23 × 10⁻¹³", "99.1%", "$0.0123"]


def test_each_result_states_its_date_model_and_sample_size():
    text = (REPO / "RESULTS.md").read_text(encoding="utf-8")
    summary = json.loads((EVALS / "summary.json").read_text())
    for m in summary["models"]:
        row = next(line for line in text.splitlines() if f"`{m['id']}`" in line and line.startswith("|"))
        assert re.search(r"\d{4}-\d{2}-\d{2}", row), row
        assert f"of {m['questions_run']}" in row, row
    report = json.loads(QUANTLIB.read_text())
    for q in report["quantlib"]:
        row = next(line for line in text.splitlines() if line.startswith(f"| {q['measure']} "))
        assert f"| {q['instruments']} |" in row, row
    assert report["generated_at"][:10] in text and report["quantlib_version"] in text


# ------------------------------------------------------------------ MODEL_CARD.md

SECTIONS = ["Intended use", "Out-of-scope use", "Components", "Assumptions", "Limitations",
            "Validation evidence", "Verification tolerance", "Human review procedure"]


def test_model_card_has_every_required_section_filled_in():
    card = (REPO / "MODEL_CARD.md").read_text(encoding="utf-8")
    assert "Skeleton" not in card
    for name in SECTIONS:
        m = re.search(rf"^## {re.escape(name)}\n(.*?)(?=^## |\Z)", card, re.M | re.S)
        assert m, name
        assert len(m.group(1).strip()) > 80, f"section {name!r} is nearly empty"


def test_every_number_in_the_model_card_traces_to_results_or_code_constants():
    led, dates = sources()
    for value, unit, label in ((100 * RELATIVE_TOLERANCE, "pct", "verifier tolerance"),
                               (MAX_MODEL_CALLS, "number", "model calls per request"),
                               (MAX_QUESTION_CHARS, "number", "question length cap")):
        led.add(value, unit, label, tool="code", args={}, method="code")
    card = (REPO / "MODEL_CARD.md").read_text(encoding="utf-8")
    assert untraced(card, led, dates) == []
