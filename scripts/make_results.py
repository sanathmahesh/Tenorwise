"""Write RESULTS.md: the measured results, generated from the evidence files. Never edit RESULTS.md by hand.

    uv run python scripts/make_results.py

Sources: docs/evidence/quantlib_report.json (scripts/quantlib_report.py) and
docs/evidence/evals/summary.json plus raw/*.jsonl (python -m tenorwise.evals report).
Only measured numbers appear, each with its date, model ID and sample size. A test
runs the project's own number verifier over the output against those files.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = REPO_ROOT / "RESULTS.md"
QUANTLIB = REPO_ROOT / "docs" / "evidence" / "quantlib_report.json"
EVALS = REPO_ROOT / "docs" / "evidence" / "evals"

SUPERSCRIPT = str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹")


def sci(x: float) -> str:
    """Three significant figures in scientific notation: 1.54 × 10⁻¹³."""
    if x == 0:
        return "0"
    mantissa, exponent = f"{x:.2e}".split("e")
    return f"{mantissa} × 10{str(int(exponent)).translate(SUPERSCRIPT)}"


def pct(fraction: float) -> str:
    return f"{100 * fraction:.1f}%"


def cost(usd: float) -> str:
    """Three significant figures, so a small cost never prints as $0.000 (D-076)."""
    return f"${usd:.3g}"


def eval_dates(model: str) -> str:
    days = sorted({json.loads(line)["finished_at"][:10]
                   for path in (EVALS / "raw").glob("*.jsonl")
                   for line in path.read_text(encoding="utf-8").splitlines()
                   if line.strip() and json.loads(line)["model"] == model})
    return days[0] if len(days) == 1 else f"{days[0]} to {days[-1]}"


def render() -> str:
    q = json.loads(QUANTLIB.read_text(encoding="utf-8"))
    s = json.loads((EVALS / "summary.json").read_text(encoding="utf-8"))
    questions = len(s["questions"])
    out = [
        "# Results",
        "",
        "Generated by `scripts/make_results.py` from `docs/evidence/quantlib_report.json` and "
        "`docs/evidence/evals/` (summary and raw results). Do not edit by hand. Every number below was measured; "
        "a test re-checks each one against those files with the project's own number verifier.",
        "",
        "## Pricing engine against QuantLib",
        "",
        f"Measured on {q['generated_at'][:10]} with QuantLib (version `{q['quantlib_version']}`), an independent open-source pricing "
        f"library, on the pinned Treasury curve for {q['data_date']}. The largest absolute difference between "
        "Tenorwise's pricing code and QuantLib, per measure:",
        "",
        "| Measure | Instruments | Largest difference | Unit |",
        "|---|---|---|---|",
    ]
    for row in q["quantlib"]:
        out.append(f"| {row['measure']} | {row['instruments']} | {sci(row['max_abs_diff'])} | {row['unit']} |")
    out += [
        "",
        "## AI analyst evals",
        "",
        f"Each model answered the same {questions} questions in 3 repeats on Sail's asap tier, graded deterministically "
        "against figures computed by the engine. Accuracy is the mean over the repeats. Cost per question is "
        "reported token usage at Sail's list prices for the day of the run, not an invoice.",
        "",
        "| Model | Accuracy | Runs passed | Cost per question | Measured on |",
        "|---|---|---|---|---|",
    ]
    for m in s["models"]:
        out.append(
            f"| `{m['id']}` | {pct(m['accuracy'])} | {m['passes']} of {m['questions_run']} | "
            f"{cost(m['cost_per_question_usd'])} | {eval_dates(m['id'])} |"
        )
    out += [
        "",
        "No answer that passed verification was wrong in these runs. That does not make the rate zero: see "
        "`docs/evidence/evals/report.md` for the one-sided upper bounds, latency and the per-question results.",
    ]
    return "\n".join(out) + "\n"


def main() -> int:
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
